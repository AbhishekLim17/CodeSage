r"""Evaluate questions about the whole repository: does the repository map put the right areas in front of the model?

For each suite the repository is indexed (incrementally), then every overview question is run twice: with ordinary
retrieval, and with the overview retriever (repository map and README added for questions it recognises as overview
questions). Scored per question and in total:

* **overview rate**: how many questions the classifier recognised (recall of the classifier on these questions);
* **area coverage**: the share of ``gold_dirs`` the context shows, either as code from inside the directory or as a
  line in the repository map;
* **in context**: a ``gold_files`` document is among the sources, and the lenient version that also accepts
  ``acceptable_files``;
* **tokens**: how large the context is.

It also checks the classifier the other way: how many of the labelled *non-overview* questions it wrongly flags.

Area coverage says whether the right areas are *mentioned*, not whether an answer built from them is good; that needs
real answers and a judge (``eval/run_answers.py``).

    python eval/run_overview_eval.py \
        --suite magnaflow  path/to/MagnaFlow  eval/questions/magnaflow_overview.jsonl \
        --suite codebase_ai .                 eval/questions/codebase_ai_overview.jsonl \
        --others eval/questions/magnaflow.jsonl eval/questions/codebase_ai.jsonl eval/questions/rich.jsonl
"""

from __future__ import annotations

import argparse
import json
import platform
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path
from statistics import fmean

from codebase_ai.config import get_settings
from codebase_ai.evaluation import EvalReport, evaluate, load_questions
from codebase_ai.index.embedder import create_embedder
from codebase_ai.index.indexer import Indexer, RepoIndex
from codebase_ai.ingest.walker import WalkLimits
from codebase_ai.retrieval.overview import OverviewRetriever
from codebase_ai.retrieval.query import is_overview_question
from codebase_ai.retrieval.retriever import Retriever


def pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.0f}%"


def summarize(report: EvalReport) -> dict[str, float | None]:
    results = report.results
    coverage = [r.area_coverage for r in results if r.area_coverage is not None]
    return {
        "questions": len(results),
        "overview_rate": fmean(1.0 if r.overview else 0.0 for r in results),
        "area_coverage": fmean(coverage) if coverage else None,
        "in_context": fmean(1.0 if r.in_context else 0.0 for r in results),
        "lenient_in_context": fmean(1.0 if r.lenient_in_context else 0.0 for r in results),
        "tokens": fmean(r.tokens for r in results),
    }


def run_suite(name: str, repo: Path, questions_file: Path, index_root: Path, embedder) -> dict:
    settings = get_settings()
    questions = load_questions(questions_file)
    index = RepoIndex(repo, index_root)
    try:
        report = Indexer(
            index,
            embedder,
            limits=WalkLimits(settings.max_file_bytes, settings.max_config_bytes),
            chunk_max_lines=settings.chunk_max_lines,
            window_lines=settings.window_lines,
            window_overlap=settings.window_overlap,
            batch_size=settings.embed_batch_size,
        ).run()
        print(f"[{name}] index: {report.files_indexed} new/changed, {report.files_unchanged} unchanged", flush=True)
        plain = Retriever(
            index,
            embedder,
            top_k=settings.retrieve_top_k,
            budget_tokens=settings.context_token_budget,
            test_penalty=settings.test_penalty,
        )
        overview = OverviewRetriever(plain, map_tokens=settings.repo_map_tokens)
        return {
            "name": name,
            "questions": questions,
            "plain": evaluate(plain, questions, name="plain retrieval"),
            "with_map": evaluate(overview, questions, name="with repository map"),
        }
    finally:
        index.close()


def render(suites: list[dict], false_positives: list[str], others: int, env: dict) -> str:
    intro = (
        f"Run on {env['date']} · {env['machine']} · embedding model `{env['embedding_model']}`. "
        "Generated by `eval/run_overview_eval.py`."
    )
    header = (
        "| Suite | Configuration | Questions | Recognised as overview | Area coverage | Gold doc in context "
        "| Lenient | Avg tokens |"
    )
    lines = [intro, "", header, "|---|---|---|---|---|---|---|---|"]
    pooled: dict[str, list] = {"plain retrieval": [], "with repository map": []}
    for suite in suites:
        for key in ("plain", "with_map"):
            report: EvalReport = suite[key]
            pooled[report.name] += report.results
            s = summarize(report)
            lines.append(
                f"| {suite['name']} | {report.name} | {s['questions']} | {pct(s['overview_rate'])} | "
                f"{pct(s['area_coverage'])} | {pct(s['in_context'])} | {pct(s['lenient_in_context'])} | "
                f"{s['tokens']:.0f} |"
            )
    for name, results in pooled.items():
        s = summarize(EvalReport(name=name, results=results))
        lines.append(
            f"| **all** | {name} | {s['questions']} | {pct(s['overview_rate'])} | {pct(s['area_coverage'])} | "
            f"{pct(s['in_context'])} | {pct(s['lenient_in_context'])} | {s['tokens']:.0f} |"
        )
    lines += ["", "Per question (with the map):", "", "| Question | Recognised | Area coverage | Gold doc in context |", "|---|---|---|---|"]
    for suite in suites:
        questions = {q.id: q for q in suite["questions"]}
        for result in suite["with_map"].results:
            lines.append(
                f"| {suite['name']}/{result.id}: {questions[result.id].question} | "
                f"{'yes' if result.overview else 'no'} | {pct(result.area_coverage)} | "
                f"{'yes' if result.lenient_in_context else 'no'} |"
            )
    lines += [
        "",
        f"Classifier, the other direction: {len(false_positives)} of {others} labelled non-overview questions "
        "were wrongly treated as overview questions"
        + (":" if false_positives else "."),
    ]
    lines += [f"- {item}" for item in false_positives]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--suite", nargs=3, action="append", metavar=("NAME", "REPO", "QUESTIONS"), required=True)
    parser.add_argument("--others", nargs="*", type=Path, default=[], help="labelled non-overview question files")
    parser.add_argument("--index-root", type=Path, default=None, help="where indexes live (default: INDEX_DIR)")
    parser.add_argument("--out-md", type=Path, default=None)
    parser.add_argument("--out-json", type=Path, default=Path(__file__).parent / "results" / "overview_eval.json")
    args = parser.parse_args()

    settings = get_settings()
    index_root = args.index_root or settings.index_dir
    embedder = create_embedder(settings)
    suites = [run_suite(n, Path(r).resolve(), Path(q), index_root, embedder) for n, r, q in args.suite]

    others = [q for path in args.others for q in load_questions(path)]
    false_positives = [f"{q.id}: {q.question}" for q in others if is_overview_question(q.question)]
    env = {
        "date": datetime.now(tz=UTC).date().isoformat(),
        "machine": platform.platform(),
        "embedding_model": embedder.model_id,
    }
    text = render(suites, false_positives, len(others), env)
    print(text)

    args.out_json.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "env": env,
        "suites": {
            s["name"]: {
                key: {"summary": summarize(s[key]), "questions": [asdict(r) for r in s[key].results]}
                for key in ("plain", "with_map")
            }
            for s in suites
        },
        "classifier_false_positives": false_positives,
        "labelled_non_overview_questions": len(others),
    }
    args.out_json.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    if args.out_md:
        args.out_md.write_text(text, encoding="utf-8")
        print(f"wrote {args.out_md}", flush=True)


if __name__ == "__main__":
    main()
