r"""Does a cross-encoder reranker improve retrieval enough to be worth its latency? (M4 ablation)

Runs the labelled natural-language questions of several repositories through the current default retrieval
(``vector`` with test demotion) and through the same retrieval followed by a reranker, and compares them question by
question with the paired statistics used for the M2 decisions (bootstrap interval on the MRR difference, sign test).
It also reports what a reranker costs: extra milliseconds per query.

    python eval/run_rerank_eval.py --reranker cross-encoder/ms-marco-MiniLM-L-6-v2 \
        --suite magnaflow  path/to/MagnaFlow  eval/questions/magnaflow.jsonl \
        --suite codebase_ai .                 eval/questions/codebase_ai.jsonl \
        --suite rich .venv/Lib/site-packages/rich eval/questions/rich.jsonl

Pass several ``--reranker`` values to compare models; ``--top-n`` sets how many candidates each re-orders. The first
run of a model downloads it from Hugging Face. Nothing is sent anywhere else.
"""

from __future__ import annotations

import argparse
import json
import platform
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path

from codebase_ai.config import get_settings
from codebase_ai.evaluation import EvalReport, evaluate, load_questions, to_markdown
from codebase_ai.index.embedder import create_embedder
from codebase_ai.index.indexer import Indexer, RepoIndex
from codebase_ai.ingest.walker import WalkLimits
from codebase_ai.metrics import paired_comparison
from codebase_ai.retrieval.reranker import CrossEncoderReranker
from codebase_ai.retrieval.retriever import Retriever

BASELINE = "vector + demote tests"


def config_names(rerankers: list[str], top_n: int) -> list[str]:
    return [BASELINE, *(f"{BASELINE} + rerank ({name}, top {top_n})" for name in rerankers)]


def run_suite(name: str, repo: Path, questions_file: Path, index_root: Path, embedder, rerankers, top_n: int) -> dict:
    settings = get_settings()
    questions = load_questions(questions_file)
    index = RepoIndex(repo, index_root)
    try:
        Indexer(
            index,
            embedder,
            limits=WalkLimits(settings.max_file_bytes, settings.max_config_bytes),
            chunk_max_lines=settings.chunk_max_lines,
            window_lines=settings.window_lines,
            window_overlap=settings.window_overlap,
            batch_size=settings.embed_batch_size,
        ).run()
        reports = []
        for config, reranker in zip(config_names([r.model_name for r in rerankers], top_n), [None, *rerankers], strict=True):
            print(f"[{name}] {config}", flush=True)
            retriever = Retriever(
                index,
                embedder,
                mode="vector",
                top_k=settings.retrieve_top_k,
                budget_tokens=settings.context_token_budget,
                test_penalty=settings.test_penalty,
                reranker=reranker,
                rerank_top=top_n,
            )
            if reranker is not None:
                reranker.score("warm up", ["load the model before timing it"])  # keep model loading out of the latency
            reports.append(evaluate(retriever, questions, name=config))
        return {"name": name, "reports": reports}
    finally:
        index.close()


def pooled(suites: list[dict]) -> list[EvalReport]:
    names = [r.name for r in suites[0]["reports"]]
    return [
        EvalReport(name=n, results=[q for s in suites for r in s["reports"] if r.name == n for q in r.results])
        for n in names
    ]


def paired_rows(reports: list[EvalReport]) -> str:
    base = reports[0]
    rows = [
        "| Reranker vs baseline | Questions | MRR difference | 95% interval | Better / worse / tied | Sign test p |",
        "|---|---|---|---|---|---|",
    ]
    for other in reports[1:]:
        r = paired_comparison([x.rank for x in other.results], [x.rank for x in base.results])
        mark = " (*)" if r.significant else ""
        rows.append(
            f"| {other.name} | {r.n} | {r.mrr_diff:+.3f}{mark} | [{r.ci_low:+.3f}, {r.ci_high:+.3f}] | "
            f"{r.better} / {r.worse} / {r.tied} | {r.sign_p:.3f} |"
        )
    rows += ["", "(*) = the 95% interval excludes zero, i.e. the difference is unlikely to be noise."]
    return "\n".join(rows)


def render(suites: list[dict], env: dict) -> str:
    all_reports = pooled(suites)
    base_ms = all_reports[0].summary["avg_ms"]
    intro = (
        f"Run on {env['date']} · {env['machine']} · embedding model `{env['embedding_model']}`. "
        "Generated by `eval/run_rerank_eval.py`."
    )
    parts = [
        intro,
        "",
        "### Pooled: natural-language questions",
        "",
        to_markdown(all_reports),
        "",
        paired_rows(all_reports),
        "",
        "Latency cost per query (mean, this machine, CPU): "
        + ", ".join(f"{r.name.split(' + rerank ')[-1]}: +{r.summary['avg_ms'] - base_ms:.0f} ms" for r in all_reports[1:])
        + ".",
    ]
    for suite in suites:
        parts += ["", f"### {suite['name']}", "", to_markdown(suite["reports"]), "", paired_rows(suite["reports"])]
    return "\n".join(parts) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--suite", nargs=3, action="append", metavar=("NAME", "REPO", "QUESTIONS"), required=True)
    parser.add_argument("--reranker", action="append", required=True, help="cross-encoder model name (repeatable)")
    parser.add_argument("--top-n", type=int, default=30, help="candidates each reranker re-orders")
    parser.add_argument("--index-root", type=Path, default=None, help="where indexes live (default: INDEX_DIR)")
    parser.add_argument("--out-md", type=Path, default=None)
    parser.add_argument("--out-json", type=Path, default=Path(__file__).parent / "results" / "rerank_eval.json")
    args = parser.parse_args()

    settings = get_settings()
    embedder = create_embedder(settings)
    rerankers = [CrossEncoderReranker(name) for name in args.reranker]
    suites = [
        run_suite(n, Path(r).resolve(), Path(q), args.index_root or settings.index_dir, embedder, rerankers, args.top_n)
        for n, r, q in args.suite
    ]
    env = {
        "date": datetime.now(tz=UTC).date().isoformat(),
        "machine": platform.platform(),
        "embedding_model": embedder.model_id,
    }
    text = render(suites, env)
    print(text)
    args.out_json.parent.mkdir(parents=True, exist_ok=True)
    args.out_json.write_text(
        json.dumps(
            {
                "env": env,
                "rerankers": args.reranker,
                "top_n": args.top_n,
                "suites": {
                    s["name"]: {r.name: {"summary": r.summary, "questions": [asdict(x) for x in r.results]} for r in s["reports"]}
                    for s in suites
                },
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    if args.out_md:
        args.out_md.write_text(text, encoding="utf-8")
        print(f"wrote {args.out_md}", flush=True)


if __name__ == "__main__":
    main()
