r"""Determinism check: the same questions answered twice, compared answer by answer (research plan, step 3.9).

    python eval/run_answers.py REPO QUESTIONS --provider ollama --model M --frozen F --limit 20 --out-json det/first.json
    python eval/run_answers.py REPO QUESTIONS --provider ollama --model M --frozen F --limit 20 --out-json det/second.json
    python eval/check_determinism.py det/first.json det/second.json --out-md det/report.md

At temperature 0 a model picks the most likely word every time, so two runs should give the same text; splitting a
model between the GPU and the CPU, or a different Ollama version, can still change it. The report gives, per question,
whether the answer is identical, how similar it is, where it first differs, and whether any score changed (grounded,
which sources were cited, precision, gold cited). Pairs of files are compared in the order given (A B [C D ...]).
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import sys
from pathlib import Path

SCORES = ("grounded", "cited", "precision", "gold_cited", "error")
SETUP = ("provider", "model", "questions_file", "retrieval")  # what must match for the comparison to mean anything


def setup_of(env: dict) -> dict:
    prompt = env.get("prompt") or {}
    return {**{k: env.get(k) for k in SETUP}, "prompt": prompt.get("name", "P1")}


def compare(first: dict, second: dict) -> list[dict]:
    """One row per question answered in both files, in the first file's order."""
    other = {row["id"]: row for row in second["results"]}
    rows = []
    for a in first["results"]:
        b = other.get(a["id"])
        if b is None:
            continue
        x, y = a.get("answer", ""), b.get("answer", "")
        offset = len(os.path.commonprefix([x, y]))
        rows.append({
            "id": a["id"],
            "identical": x == y,
            "similarity": difflib.SequenceMatcher(None, x, y, autojunk=False).ratio(),
            "first_difference": None if x == y else offset,
            "context": None if x == y else (x[max(0, offset - 40): offset + 60], y[max(0, offset - 40): offset + 60]),
            "scores_changed": [k for k in SCORES if a.get(k) != b.get(k)],
        })
    return rows


def report(pairs: list[tuple[Path, Path]]) -> tuple[str, int]:
    lines = ["# Determinism check", "", "Generated by `eval/check_determinism.py`.", ""]
    differing = 0
    for first_path, second_path in pairs:
        first, second = (json.loads(p.read_text(encoding="utf-8")) for p in (first_path, second_path))
        rows = compare(first, second)
        same = sum(r["identical"] for r in rows)
        changed = sum(bool(r["scores_changed"]) for r in rows)
        differing += len(rows) - same
        lines += [f"## {first_path.name} vs {second_path.name}", ""]
        a, b = setup_of(first["env"]), setup_of(second["env"])
        if a != b:
            differ = ", ".join(k for k in a if a[k] != b[k])
            warning = f"**Warning: the two runs were not set up the same way** ({differ} differ), so differences may "
            lines += [warning + "not be non-determinism.", ""]
        summary = f"**{same} of {len(rows)} answers identical**; scores changed for {changed}."
        lines += [
            f"Model `{a['model']}`, prompt {a['prompt']}: {summary}", "",
            "| Question | Identical | Similarity | First difference at character | Scores that changed |",
            "|---|---|---|---|---|",
        ]
        for r in rows:
            where = "" if r["identical"] else str(r["first_difference"])
            lines.append(f"| {r['id']} | {'yes' if r['identical'] else 'no'} | {r['similarity']:.3f} | {where} | "
                         f"{', '.join(r['scores_changed']) or '-'} |")
        for r in [r for r in rows if not r["identical"]][:3]:
            lines += ["", f"**{r['id']}**, where the two answers part:", "", "```text", f"first:  ...{r['context'][0]}...",
                      f"second: ...{r['context'][1]}...", "```"]
        lines.append("")
    return "\n".join(lines), differing


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("files", nargs="+", type=Path, help="result files in pairs: FIRST SECOND [FIRST SECOND ...]")
    parser.add_argument("--out-md", type=Path, default=None)
    args = parser.parse_args(argv)
    if len(args.files) % 2:
        print("error: give the result files in pairs (first run, second run)", file=sys.stderr)
        return 2
    text, differing = report(list(zip(args.files[::2], args.files[1::2], strict=True)))
    print(text)
    if args.out_md:
        args.out_md.write_text(text, encoding="utf-8")
    print(f"{differing} answer(s) differ between the runs." if differing else "Every answer is identical in both runs.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
