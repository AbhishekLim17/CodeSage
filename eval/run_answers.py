r"""Answer-quality evaluation: answer the labelled questions with a real model and score the answers (M4).

This calls a language model once per question (and once more per answer if a judge is given), so it costs money with a
hosted provider and sends retrieved code to that provider. It will not start without ``--yes`` when either model is
hosted; without it, it prints exactly what it would do and exits.

    python eval/run_answers.py path/to/repo eval/questions/magnaflow.jsonl \
        --provider anthropic --model claude-sonnet-5-5 \
        --judge-provider openai --judge-model gpt-4o \
        --limit 20 --export-sample 10 --yes

What is scored is in ``src/codebase_ai/answer_eval.py``: grounded rate, citation validity and precision, whether the gold
file was cited, and (with a judge) faithfulness. Use a judge from a different model family than the answering model
where you can; a model grading its own answers is lenient. To check the judge itself, export a sample, grade it by hand
without looking at the judge's verdicts, and compare:

    python eval/run_answers.py --check-sample my_verdicts.json --results eval/results/answer_eval.json
"""

from __future__ import annotations

import argparse
import json
import platform
import sys
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path

from codebase_ai.answer_eval import (
    AnswerReport,
    AnswerResult,
    Judgement,
    agreement,
    export_sample,
    run_answer_eval,
    sample_for_review,
)
from codebase_ai.config import get_settings
from codebase_ai.evaluation import EvalQuestion, load_questions
from codebase_ai.index.embedder import EmbeddingError, create_embedder
from codebase_ai.index.indexer import RepoIndex
from codebase_ai.llm.base import LLMProvider, ProviderError, create_provider
from codebase_ai.rag.answerer import context_budget_for, create_answerer
from codebase_ai.retrieval.retriever import RetrievalError

DEFAULT_OUT = Path(__file__).parent / "results" / "answer_eval.json"


def pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.0f}%"


def plan_text(
    questions: list[EvalQuestion], generator: LLMProvider, judge: LLMProvider | None, budget: int, max_tokens: int
) -> str:
    """What the run will do, in plain words, before anything is sent."""
    first = (
        f"{len(questions)} question(s). For each: one answer from {generator.name} ({generator.model}), "
        f"with up to about {budget} tokens of retrieved code in the prompt and up to {max_tokens} tokens of output."
    )
    lines = [first]
    if judge is not None:
        lines.append(
            f"Then one judgement per answer from {judge.name} ({judge.model}), which is sent the question, the answer "
            "and the code the answer cites."
        )
    hosted = [p for p in (generator, judge) if p is not None and p.sends_code_off_machine]
    if hosted:
        names = ", ".join(sorted({p.name for p in hosted}))
        lines.append(f"Retrieved code from the repository will be sent to: {names}. This uses your account there.")
    if judge is not None and (judge.name, judge.model) == (generator.name, generator.model):
        lines.append("Warning: the judge is the same model as the answerer; self-graded scores are usually too kind.")
    return "\n".join(lines)


def render(report: AnswerReport, env: dict) -> str:
    s = report.summary
    intro = (
        f"Run on {env['date']} · {env['machine']} · answerer `{env['provider']}/{env['model']}` · judge `{env['judge']}` "
        f"· embedding model `{env['embedding_model']}`. Generated by `eval/run_answers.py`."
    )
    lines = [
        intro,
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| Questions (answered / failed) | {s['questions']} ({s['questions'] - s['errors']} / {s['errors']}) |",
        f"| Grounded: cites at least one supplied source | {pct(s['grounded_rate'])} |",
        f"| Citation validity: cited numbers that exist | {pct(s['citation_validity'])} |",
        f"| Citation precision: cited sources that are relevant | {pct(s['citation_precision'])} |",
        f"| Cites a gold or acceptable file | {pct(s['gold_cited_rate'])} |",
        f"| Supplied sources left uncited (mean) | {pct(s['uncited_share'])} |",
        f"| Mentions a location it was not shown | {pct(s['unverified_location_rate'])} |",
        f"| Refused / cut off at the output limit | {pct(s['refusal_rate'])} / {pct(s['truncation_rate'])} |",
        f"| Faithfulness (judge; {s['judged']} judged): mean of 1 / 0.5 / 0 | {pct(s['faithfulness'])} |",
        f"| Judged fully supported | {pct(s['supported_rate'])} |",
    ]
    if s["avg_tokens_in"] is not None:
        lines.append(f"| Tokens per answer (in / out) | {s['avg_tokens_in']:.0f} / {s['avg_tokens_out'] or 0:.0f} |")
    lines += ["", "| Question | Grounded | Precision | Gold cited | Verdict |", "|---|---|---|---|---|"]
    for r in report.results:
        verdict = r.judgement.verdict or ("error" if r.error else "-")
        lines.append(
            f"| {r.id}: {r.question} | {'yes' if r.grounded else 'no'} | {pct(r.precision)} | "
            f"{'yes' if r.gold_cited else 'no'} | {verdict} |"
        )
    return "\n".join(lines) + "\n"


def results_payload(report: AnswerReport, env: dict) -> dict:
    return {"env": env, "summary": report.summary, "results": [asdict(r) for r in report.results]}


def load_results(path: Path) -> list[AnswerResult]:
    """Read back the results file written by a run (used to check the judge against a human)."""
    rows = json.loads(path.read_text(encoding="utf-8"))["results"]
    return [
        AnswerResult(
            **{**row, "cited": tuple(row["cited"]), "judgement": Judgement(**{**row["judgement"], "unsupported_claims": tuple(row["judgement"]["unsupported_claims"])})}
        )
        for row in rows
    ]


def check_sample(human_file: Path, results_file: Path) -> str:
    human = json.loads(human_file.read_text(encoding="utf-8"))
    result = agreement(load_results(results_file), human)
    if result.compared == 0:
        return "No overlap: none of the verdicts in the file match a judged answer in the results."
    return (
        f"Compared {result.compared} answer(s): the judge and the human gave the same verdict on {result.matching} "
        f"({pct(result.rate)}), and were within one step on {result.within_one_step}."
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("repo", nargs="?", type=Path)
    parser.add_argument("questions", nargs="?", type=Path)
    parser.add_argument("--provider", default=None, help="answering provider (default: LLM_PROVIDER)")
    parser.add_argument("--model", default=None)
    parser.add_argument("--judge-provider", default=None, help="enables the faithfulness judge")
    parser.add_argument("--judge-model", default=None)
    parser.add_argument("--mode", default=None, choices=["vector", "keyword", "hybrid"])
    parser.add_argument("--limit", type=int, default=None, help="only the first N questions")
    parser.add_argument("--types", default=None, help="comma-separated question types to include")
    parser.add_argument("--yes", action="store_true", help="go ahead even though code is sent to a hosted provider")
    parser.add_argument("--export-sample", type=int, default=0, metavar="N", help="write N judged answers for a hand check")
    parser.add_argument("--index-root", type=Path, default=None)
    parser.add_argument("--out-json", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--out-md", type=Path, default=None)
    parser.add_argument("--check-sample", type=Path, default=None, metavar="HUMAN_JSON")
    parser.add_argument("--results", type=Path, default=DEFAULT_OUT, help="results file for --check-sample")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.check_sample is not None:
        print(check_sample(args.check_sample, args.results))
        return 0
    if args.repo is None or args.questions is None:
        print("error: a repository and a question file are required", file=sys.stderr)
        return 2

    settings = get_settings()
    questions = load_questions(args.questions)
    if args.types:
        wanted = {t.strip() for t in args.types.split(",")}
        questions = [q for q in questions if q.type in wanted]
    if args.limit is not None:
        questions = questions[: args.limit]
    if not questions:
        print("error: no questions selected", file=sys.stderr)
        return 2

    try:
        generator = create_provider(settings, provider=args.provider, model=args.model)
        judge = (
            create_provider(settings, provider=args.judge_provider, model=args.judge_model)
            if args.judge_provider or args.judge_model
            else None
        )
    except ProviderError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    budget = context_budget_for(generator, settings.context_token_budget, settings.answer_max_tokens)
    print(plan_text(questions, generator, judge, budget, settings.answer_max_tokens))
    if any(p.sends_code_off_machine for p in (generator, judge) if p is not None) and not args.yes:
        print("\nNot started: re-run with --yes to send code to the provider(s) above.", file=sys.stderr)
        return 2

    repo = args.repo.resolve()
    index = RepoIndex(repo, args.index_root or settings.index_dir)
    try:
        if not index.is_built():
            print(f"error: no index for {repo}. Run: codebase-ai index {repo}", file=sys.stderr)
            return 1
        mode = args.mode or settings.retrieval_mode
        try:
            embedder = None if mode == "keyword" else create_embedder(settings)
            answerer = create_answerer(settings, index, embedder, generator, mode=mode)
            report = run_answer_eval(
                answerer,
                questions,
                judge=judge,
                name=f"{generator.name}/{generator.model}",
                progress=lambda n, total, r: print(
                    f"  [{n}/{total}] {r.id}: " + (f"failed: {r.error}" if r.error else f"grounded={r.grounded} verdict={r.judgement.verdict}"),
                    flush=True,
                ),
            )
        except (ProviderError, EmbeddingError, RetrievalError) as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 1
    finally:
        index.close()

    env = {
        "date": datetime.now(tz=UTC).date().isoformat(),
        "machine": platform.platform(),
        "provider": generator.name,
        "model": generator.model,
        "judge": f"{judge.name}/{judge.model}" if judge else "none",
        "embedding_model": embedder.model_id if embedder else "none (keyword)",
        "questions_file": str(args.questions),
    }
    text = render(report, env)
    print("\n" + text)
    args.out_json.parent.mkdir(parents=True, exist_ok=True)
    args.out_json.write_text(json.dumps(results_payload(report, env), indent=2), encoding="utf-8")
    if args.out_md:
        args.out_md.write_text(text, encoding="utf-8")
    if args.export_sample:
        sample_path = args.out_json.with_name(args.out_json.stem + "_sample.md")
        sample_path.write_text(export_sample(sample_for_review(report.results, args.export_sample)), encoding="utf-8")
        print(f"wrote {sample_path} for the hand check")
    return 0


if __name__ == "__main__":
    sys.exit(main())
