r"""Power of the two powered hypotheses by simulation (research plan, step 3.8; replaces the estimates in protocol 8).

    python eval/power_simulation.py --out-md research/POWER_SIMULATION.md

* **H2** (C2): P1 is non-inferior to P0 on "fully correct" if the lower end of the 95% interval of the paired
  difference is above the margin. Simulated for several sample sizes, rates of disagreement between the two prompts
  (the share of questions where exactly one of the two answers is fully correct) and true differences.
* **H1** (C1, one model): P1 raises the grounded rate; exact McNemar test, at 0.05 and at 0.05/8 (the smallest Holm
  threshold when all eight primary tests are run).

Questions are simulated as independent; the real analysis also resamples repositories, which widens the interval when
repositories differ, so these figures are the best case. The interval here is the normal (Wald) one for a paired
difference, which the bootstrap of the real analysis matches closely at these sample sizes.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
from scipy import stats

SIMULATIONS = 20_000


def paired_counts(rng: np.random.Generator, n: int, discordance: float, difference: float) -> tuple[np.ndarray, np.ndarray]:
    """Counts of questions where only P1 is right (b) and where only P0 is right (c), for ``SIMULATIONS`` studies."""
    if abs(difference) > discordance:
        raise ValueError("the difference cannot exceed the share of discordant questions")
    b, c = (discordance + difference) / 2, (discordance - difference) / 2
    counts = rng.multinomial(n, [b, c, 1 - b - c], size=SIMULATIONS)
    return counts[:, 0], counts[:, 1]


def noninferiority_power(rng, n: int, discordance: float, difference: float, margin: float) -> float:
    b, c = paired_counts(rng, n, discordance, difference)
    estimate = (b - c) / n
    se = np.sqrt(np.maximum(b + c - (b - c) ** 2 / n, 0)) / n
    return float(np.mean(estimate - 1.96 * se > margin))


def mcnemar_power(rng, n: int, discordance: float, difference: float, alpha: float) -> float:
    b, c = paired_counts(rng, n, discordance, difference)
    pvalues = np.minimum(1.0, 2 * stats.binom.cdf(np.minimum(b, c), b + c, 0.5))
    return float(np.mean((pvalues < alpha) & (b > c)))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--margin", type=float, default=-0.10)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--out-md", type=Path, default=None)
    args = parser.parse_args(argv)
    rng = np.random.default_rng(args.seed)

    lines = [
        "# Power simulation", "",
        (f"Generated by `eval/power_simulation.py` ({SIMULATIONS:,} simulated studies per cell, seed {args.seed}). "
         "Questions are independent here; repositories that differ make the real interval wider, so read these as the "
         "best case."), "",
        f"## H2: non-inferiority of P1 on fully correct (margin {args.margin:+.0%})", "",
        ("Probability that the 95% interval's lower end is above the margin. *Disagreement* is the share of questions "
         "where exactly one of the P0 and P1 answers is fully correct (the pilot had 2 of 10)."), "",
        "| Questions | Disagreement | True difference 0 | True -3 points | True -5 points |", "|---|---|---|---|---|",
    ]
    for n in (100, 150, 200):
        for discordance in (0.10, 0.15, 0.20, 0.25, 0.30):
            cells = [noninferiority_power(rng, n, discordance, d, args.margin) for d in (0.0, -0.03, -0.05)]
            lines.append(f"| {n} | {discordance:.0%} | " + " | ".join(f"{p:.0%}" for p in cells) + " |")
    lines += [
        "", "## H1: P1 raises the grounded rate (one model, exact McNemar)", "",
        ("Probability of a significant gain at 0.05 / at 0.05/8 (the strictest Holm step with eight primary tests), "
         "with 150 questions. *Disagreement* is the share of questions grounded under exactly one prompt."), "",
        "| True gain | Disagreement | at 0.05 | at 0.05/8 |", "|---|---|---|---|",
    ]
    for gain in (0.05, 0.10, 0.20):
        for discordance in (0.15, 0.25, 0.35):
            if gain <= discordance:
                powers = [mcnemar_power(rng, 150, discordance, gain, a) for a in (0.05, 0.05 / 8)]
                lines.append(f"| {gain:+.0%} | {discordance:.0%} | {powers[0]:.0%} | {powers[1]:.0%} |")
    text = "\n".join(lines) + "\n"
    print(text)
    if args.out_md:
        args.out_md.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
