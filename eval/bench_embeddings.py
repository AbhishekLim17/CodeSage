"""Compare embedding models on a labelled question set (M1 model-selection benchmark).

For each candidate model: index the target repo into a throw-away directory, ask every question, turn the ranked
chunks into a ranked list of files, and record where the first gold file lands. A keyword-only (BM25) run over the
same chunks is included as a reference point. Nothing is written into the target repo.

    python eval/bench_embeddings.py PATH/TO/REPO \
        --models BAAI/bge-small-en-v1.5,sentence-transformers/all-MiniLM-L6-v2 \
        --out-md docs/EMBEDDING_BENCHMARK.md
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import tempfile
import time
from datetime import UTC, datetime
from pathlib import Path

from codebase_ai.index.embedder import LocalEmbedder
from codebase_ai.index.indexer import Indexer, RepoIndex
from codebase_ai.metrics import DEFAULT_KS, first_gold_rank, summarize, unique_in_order
from codebase_ai.retrieval.retriever import search_keyword, search_vector

CHUNKS_PER_QUERY = 40  # enough chunks that de-duplicating to files still leaves a ranking of ~10 files
DEFAULT_MODELS = (
    "sentence-transformers/all-MiniLM-L6-v2",
    "BAAI/bge-small-en-v1.5",
    "Snowflake/snowflake-arctic-embed-s",
    "intfloat/e5-small-v2",
    "BAAI/bge-base-en-v1.5",
)


def load_questions(path: Path) -> list[dict]:
    """The questions with a file to find; unanswerable ones are left out (there is nothing to retrieve)."""
    rows = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    return [q for q in rows if q.get("type") != "unanswerable"]


def by_type(questions: list[dict], ranks: list[int | None]) -> dict[str, dict[str, float]]:
    out = {}
    for kind in sorted({q["type"] for q in questions}):
        subset = [r for q, r in zip(questions, ranks, strict=True) if q["type"] == kind]
        out[kind] = summarize(subset)
    return out


def run_keyword(index: RepoIndex, questions: list[dict]) -> dict:
    ranks, started = [], time.perf_counter()
    for q in questions:
        files = unique_in_order(c.path for c, _ in search_keyword(index, q["question"], CHUNKS_PER_QUERY))
        ranks.append(first_gold_rank(files[:10], q["gold_files"]))
    return {
        "name": "keyword only (BM25, no model)",
        "ranks": ranks,
        "summary": summarize(ranks),
        "by_type": by_type(questions, ranks),
        "query_ms": (time.perf_counter() - started) / len(questions) * 1000,
    }


def run_model(repo: Path, model_name: str, questions: list[dict], work_dir: Path | None, keyword_too: bool) -> dict:
    embedder = LocalEmbedder(model_name, batch_size=32)
    with tempfile.TemporaryDirectory(dir=work_dir, ignore_cleanup_errors=True) as tmp:
        index = RepoIndex(repo, tmp)
        try:
            started = time.perf_counter()
            report = Indexer(index, embedder, batch_size=32).run(full=True)
            index_seconds = time.perf_counter() - started
            print(f"  indexed {report.files_indexed} files / {report.chunks_added} chunks in {index_seconds:.0f}s", flush=True)

            ranks, per_question, started = [], [], time.perf_counter()
            for q in questions:
                results = search_vector(index, embedder, q["question"], CHUNKS_PER_QUERY)
                files = unique_in_order(c.path for c, _ in results)[:10]
                rank = first_gold_rank(files, q["gold_files"])
                ranks.append(rank)
                per_question.append({"id": q["id"], "rank": rank, "top3": files[:3]})
            query_ms = (time.perf_counter() - started) / len(questions) * 1000

            result = {
                "name": model_name,
                "dim": embedder.dim,
                "max_seq_length": int(embedder._load().max_seq_length),
                "chunks": report.chunks_added,
                "files": report.files_indexed,
                "index_seconds": index_seconds,
                "query_ms": query_ms,
                "ranks": ranks,
                "per_question": per_question,
                "summary": summarize(ranks),
                "by_type": by_type(questions, ranks),
            }
            keyword = run_keyword(index, questions) if keyword_too else None
        finally:
            index.close()
    return {"model": result, "keyword": keyword}


def pct(value: float) -> str:
    return f"{value * 100:.0f}%"


def render_markdown(repo: Path, questions: list[dict], results: list[dict], keyword: dict | None, env: dict) -> str:
    ranked = sorted(results, key=lambda r: (-r["summary"]["mrr"], -r["summary"]["hit@5"], r["index_seconds"]))
    kinds = sorted({q["type"] for q in questions})
    type_counts = ", ".join(f"{sum(1 for q in questions if q['type'] == kind)} {kind}" for kind in kinds)
    intro = (
        f"Run on {env['date']} · {env['machine']} · {env['device']}. "
        "Generated by `eval/bench_embeddings.py`; raw per-question results are in "
        "`eval/results/embedding_bench.json` (not committed)."
    )
    target = (
        f"- **Target repo:** `{repo.name}` — {ranked[0]['files']} indexable files, {ranked[0]['chunks']} chunks "
        "(React/JavaScript app plus docs, Firestore rules and scripts)."
    )
    question_line = (
        f"- **Questions:** {len(questions)} hand-written natural-language questions, "
        f"each with 1–3 gold files ({type_counts})."
    )
    metric = (
        "- **Metric:** chunks are ranked by similarity, collapsed to a ranked list of *files*, and scored on where "
        "the first gold file lands. `Hit@k` = share of questions with a gold file in the top k files; "
        "`MRR` = mean reciprocal rank (cut at 10)."
    )
    candidates = (
        "- **Candidates:** general-purpose sentence-embedding models that load *without* `trust_remote_code`. "
        "Code-specific embedding models were excluded because the ones considered require executing code "
        "shipped with the model download."
    )
    lines = [
        "# Embedding model benchmark (M1)",
        "",
        intro,
        "",
        "## Setup",
        "",
        target,
        question_line,
        metric,
        "- **Retrieval:** vector search only, top 40 chunks per query. Hybrid search and reranking are M2.",
        candidates,
        "",
        "## Results",
        "",
        "| Model | Hit@1 | Hit@3 | Hit@5 | Hit@10 | MRR | Dim | Max tokens | Index time | ms/query |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in ranked:
        s = r["summary"]
        lines.append(
            f"| `{r['name']}` | {pct(s['hit@1'])} | {pct(s['hit@3'])} | {pct(s['hit@5'])} | {pct(s['hit@10'])} | "
            f"{s['mrr']:.3f} | {r['dim']} | {r['max_seq_length']} | {r['index_seconds']:.0f}s | {r['query_ms']:.0f} |"
        )
    if keyword:
        s = keyword["summary"]
        lines.append(
            f"| *{keyword['name']}* | {pct(s['hit@1'])} | {pct(s['hit@3'])} | {pct(s['hit@5'])} | {pct(s['hit@10'])} | "
            f"{s['mrr']:.3f} | — | — | — | {keyword['query_ms']:.0f} |"
        )
    lines += ["", "## Hit@5 by question type", "", "| Model | " + " | ".join(kinds) + " |", "|---|" + "---|" * len(kinds)]
    for r in ranked:
        lines.append(f"| `{r['name']}` | " + " | ".join(pct(r["by_type"][k]["hit@5"]) for k in kinds) + " |")
    if keyword:
        lines.append(f"| *{keyword['name']}* | " + " | ".join(pct(keyword["by_type"][k]["hit@5"]) for k in kinds) + " |")

    best = ranked[0]
    misses = [
        f"- `{q['id']}` — {q['question']}  \n  gold: {', '.join(f'`{g}`' for g in q['gold_files'])}; "
        f"got: {', '.join(f'`{f}`' for f in pq['top3']) or 'nothing'}"
        for q, pq in zip(questions, best["per_question"], strict=True)
        if pq["rank"] is None or pq["rank"] > 5
    ]
    lines += ["", f"## Questions `{best['name']}` missed (no gold file in the top 5)", ""]
    lines += misses or ["None."]
    lines += ["", ANALYSIS_HEADING, "", "_(write the interpretation here; it is kept when this file is regenerated)_", ""]
    return "\n".join(lines)


ANALYSIS_HEADING = "## Reading the numbers"


def keep_analysis(existing: str, regenerated: str) -> str:
    """Carry the hand-written analysis section over from the previous report into a regenerated one."""
    if ANALYSIS_HEADING in existing and ANALYSIS_HEADING in regenerated:
        return regenerated.split(ANALYSIS_HEADING)[0] + ANALYSIS_HEADING + existing.split(ANALYSIS_HEADING, 1)[1]
    return regenerated


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("repo", type=Path)
    parser.add_argument("--questions", type=Path, default=Path(__file__).parent / "questions" / "magnaflow.jsonl")
    parser.add_argument("--models", default=",".join(DEFAULT_MODELS), help="comma-separated sentence-transformers ids")
    parser.add_argument("--work-dir", type=Path, default=None, help="where throw-away indexes are created")
    parser.add_argument("--out-md", type=Path, default=None)
    parser.add_argument("--out-json", type=Path, default=Path(__file__).parent / "results" / "embedding_bench.json")
    args = parser.parse_args()

    repo = args.repo.resolve()
    questions = load_questions(args.questions)
    models = [m.strip() for m in args.models.split(",") if m.strip()]
    print(f"{len(questions)} questions, {len(models)} models, repo {repo}", flush=True)

    results, keyword = [], None
    for i, name in enumerate(models):
        print(f"[{i + 1}/{len(models)}] {name}", flush=True)
        outcome = run_model(repo, name, questions, args.work_dir, keyword_too=keyword is None)
        results.append(outcome["model"])
        keyword = keyword or outcome["keyword"]
        s = outcome["model"]["summary"]
        print("  " + "  ".join(f"{k}={v:.2f}" for k, v in s.items()), flush=True)

    try:
        import torch

        device = "GPU" if torch.cuda.is_available() else "CPU only"
    except ImportError:
        device = "CPU only"
    env = {"date": datetime.now(tz=UTC).date().isoformat(), "machine": platform.platform(), "device": device}
    args.out_json.parent.mkdir(parents=True, exist_ok=True)
    args.out_json.write_text(
        json.dumps({"env": env, "ks": DEFAULT_KS, "models": results, "keyword": keyword}, indent=2), encoding="utf-8"
    )
    if args.out_md:
        report = render_markdown(repo, questions, results, keyword, env)
        if args.out_md.exists():
            report = keep_analysis(args.out_md.read_text(encoding="utf-8"), report)
        args.out_md.write_text(report, encoding="utf-8")
        print(f"wrote {args.out_md}", flush=True)
    print(f"median index time {statistics.median(r['index_seconds'] for r in results):.0f}s; results in {args.out_json}")


if __name__ == "__main__":
    main()
